local plugin = require('73')
plugin.register_adapter('auto_fixture', require('73.adapters.fake').new('new'))
plugin.setup({ harness = 'auto_fixture', auto_apply = true })
local buf = vim.api.nvim_create_buf(true, false)
vim.api.nvim_set_current_buf(buf)
vim.api.nvim_buf_set_lines(buf, 0, -1, true, { 'old' })
local handle = plugin.edit('replace', { range = { start = { 0, 0 }, ['end'] = { 0, 3 } } })
vim.wait(20, function() return false end)
assert(handle.status() == 'accepted')
assert(vim.api.nvim_get_current_buf() == buf)
assert(vim.api.nvim_buf_get_lines(buf, 0, 1, true)[1] == 'new')
vim.cmd('undo')
assert(vim.api.nvim_buf_get_lines(buf, 0, 1, true)[1] == 'old')
handle = plugin.edit('preview', { range = { start = { 0, 0 }, ['end'] = { 0, 3 } }, auto_apply = false })
vim.wait(20, function() return false end)
assert(handle.status() == 'preview')
handle.reject()
vim.api.nvim_set_current_buf(buf)
handle = plugin.edit('stale', { range = { start = { 0, 0 }, ['end'] = { 0, 3 } } })
vim.api.nvim_buf_set_text(buf, 0, 0, 0, 0, { 'changed' })
vim.wait(20, function() return false end)
assert(handle.status() == 'failed')
assert(not plugin.toggle_auto_apply())
plugin.setup({})
print('73 automatic acceptance checks passed')
